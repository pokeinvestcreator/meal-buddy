export default function BottomNav({ activeTab, setActiveTab, groceryList }) {
  const unchecked = Object.values(groceryList || {}).filter(i => !i.checked).length

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-40 bg-stone-900 border-t border-stone-800 safe-bottom">
      <div className="flex items-stretch h-16">
        {TABS.map(tab => {
          const isActive = activeTab === tab.id
          return (
            <button
              key={tab.id}
              onClick={() => setActiveTab(tab.id)}
              className={`flex-1 flex flex-col items-center justify-center gap-0.5 relative transition-colors ${
                isActive ? 'text-emerald-400' : 'text-stone-400'
              }`}
            >
              <div className="relative">
                {tab.icon}
                {tab.id === 'grocery' && unchecked > 0 && (
                  <span className="absolute -top-1 -right-2 bg-amber-500 text-white text-[10px] font-bold rounded-full min-w-[16px] h-4 flex items-center justify-center px-1">
                    {unchecked > 99 ? '99+' : unchecked}
                  </span>
                )}
              </div>
              <span className={`text-[10px] font-medium ${isActive ? 'text-emerald-400' : 'text-stone-500'}`}>
                {tab.label}
              </span>
              {isActive && (
                <span className="absolute top-0 left-1/2 -translate-x-1/2 w-8 h-0.5 bg-emerald-400 rounded-full" />
              )}
            </button>
          )
        })}
      </div>
    </nav>
  )
}
